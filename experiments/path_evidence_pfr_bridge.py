"""Finite-horizon path-evidence probes for PFR Internal Guidance.

The helpers in this module deliberately separate two objects:

* the deployed PFR revision, which is a finite future weak-head query; and
* a deterministic, finite-horizon proxy for the Feynman--Kac evidence value.

The latter is only a probe.  It drops the stochastic expectation in the exact
value function and follows one Euler step of the nominal IG characteristic.
It must therefore not be described as the exact Doob correction.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Callable

import torch


Tensor = torch.Tensor
PairEvaluator = Callable[[Tensor, Tensor], tuple[Tensor, Tensor]]
GammaEvaluator = Callable[[float], float]


@dataclass(frozen=True)
class SampleProjection:
    parallel: Tensor
    orthogonal: Tensor
    coefficient: Tensor


@dataclass(frozen=True)
class EvidenceGradient:
    gradient: Tensor
    strong: Tensor
    weak: Tensor
    guided: Tensor
    current_rate: Tensor
    future_rate: Tensor
    value: Tensor
    future_state: Tensor
    future_time: Tensor


def sample_rms(value: Tensor) -> Tensor:
    if value.ndim < 2:
        raise ValueError("sample_rms expects batch and feature dimensions")
    return value.float().flatten(1).square().mean(dim=1).sqrt()


def sample_cosine(left: Tensor, right: Tensor) -> Tensor:
    if left.shape != right.shape or left.ndim < 2:
        raise ValueError("cosine inputs must have identical batched shapes")
    return torch.nn.functional.cosine_similarity(
        left.float().flatten(1),
        right.float().flatten(1),
        dim=1,
        eps=1e-12,
    )


def project_per_sample(value: Tensor, direction: Tensor) -> SampleProjection:
    """Orthogonally project ``value`` onto each sample's ``direction`` line."""

    if value.shape != direction.shape or value.ndim < 2:
        raise ValueError("projection inputs must have identical batched shapes")
    value_flat = value.float().flatten(1)
    direction_flat = direction.float().flatten(1)
    numerator = (value_flat * direction_flat).sum(dim=1)
    denominator = direction_flat.square().sum(dim=1)
    tiny = torch.finfo(value_flat.dtype).tiny
    coefficient_flat = torch.where(
        denominator > tiny,
        numerator / denominator.clamp_min(tiny),
        torch.zeros_like(numerator),
    )
    coefficient = coefficient_flat.reshape(
        len(value), *([1] * (value.ndim - 1))
    ).to(dtype=value.dtype, device=value.device)
    parallel = coefficient * direction
    return SampleProjection(
        parallel=parallel,
        orthogonal=value - parallel,
        coefficient=coefficient_flat,
    )


def project_to_forward_ray(value: Tensor, direction: Tensor) -> SampleProjection:
    """Project onto the non-negative ray generated by ``direction``."""

    line = project_per_sample(value, direction)
    coefficient_flat = line.coefficient.clamp_min(0.0)
    coefficient = coefficient_flat.reshape(
        len(value), *([1] * (value.ndim - 1))
    ).to(dtype=value.dtype, device=value.device)
    parallel = coefficient * direction
    return SampleProjection(
        parallel=parallel,
        orthogonal=value - parallel,
        coefficient=coefficient_flat,
    )


def match_sample_rms(value: Tensor, reference: Tensor) -> Tensor:
    if value.shape != reference.shape:
        raise ValueError("RMS matching inputs must have identical shapes")
    value_rms = sample_rms(value)
    reference_rms = sample_rms(reference)
    tiny = torch.finfo(value_rms.dtype).tiny
    scale = torch.where(
        value_rms > tiny,
        reference_rms / value_rms.clamp_min(tiny),
        torch.zeros_like(value_rms),
    )
    scale = scale.reshape(len(value), *([1] * (value.ndim - 1))).to(
        dtype=value.dtype, device=value.device
    )
    return scale * value


def normalized_flow_evidence_rate(
    velocity_gap: Tensor,
    *,
    time_value: Tensor,
    beta: float,
) -> Tensor:
    """Per-coordinate Feynman--Kac running cost in linear-flow time.

    For ``z_t=t*x+(1-t)*eps``, converting

        0.5*beta*(beta-1)*||score_strong-score_weak||^2 d(tau)

    from heat variance ``tau=((1-t)/t)^2`` to increasing flow time gives

        beta*(beta-1)*t/(1-t)*||velocity_gap||^2 dt.

    A feature mean replaces the total squared norm for numerical scale.  This
    changes only a global positive factor and hence leaves every direction,
    projection fraction, and RMS-matched correction unchanged.
    """

    if velocity_gap.ndim < 2:
        raise ValueError("velocity_gap must have batch and feature dimensions")
    beta = float(beta)
    if beta < 1.0:
        raise ValueError("beta must be at least one")
    time_tensor = torch.as_tensor(
        time_value, dtype=velocity_gap.dtype, device=velocity_gap.device
    )
    if time_tensor.ndim == 0:
        time_tensor = time_tensor.expand(len(velocity_gap))
    if time_tensor.shape != (len(velocity_gap),):
        raise ValueError("time_value must be scalar or have shape [batch]")
    if torch.any((time_tensor < 0.0) | (time_tensor >= 1.0)):
        raise ValueError("flow time must lie in [0,1)")
    gap_energy = velocity_gap.float().flatten(1).square().mean(dim=1)
    coefficient = beta * (beta - 1.0) * time_tensor.float() / (1.0 - time_tensor.float())
    return coefficient * gap_energy


def finite_horizon_nominal_evidence_gradient(
    state: Tensor,
    time_value: Tensor,
    *,
    horizon: float,
    intervention_time: float,
    evaluate_pair: PairEvaluator,
    gamma_at: GammaEvaluator,
    create_graph: bool = False,
) -> EvidenceGradient:
    """Differentiate a two-point nominal path-evidence quadrature.

    The proxy is

        V_H(z,t) = H/2 * (c(z,t) + c(z + H*G(z,t), t+H)),

    with ``H`` tapered at ``intervention_time`` and ``G`` equal to ordinary
    IG.  It is a deterministic one-step approximation to a future evidence
    value, not the stochastic Feynman--Kac value itself.
    """

    if not state.requires_grad:
        raise ValueError("state must require gradients")
    if not 0.0 < float(horizon):
        raise ValueError("horizon must be positive")
    if not 0.0 < float(intervention_time) < 1.0:
        raise ValueError("intervention_time must lie in (0,1)")
    scalar_time = float(time_value.detach().float().item())
    step = min(float(horizon), float(intervention_time) - scalar_time)
    if step <= 0.0:
        zeros = torch.zeros_like(state)
        zero_rate = torch.zeros(len(state), device=state.device, dtype=torch.float32)
        strong, weak = evaluate_pair(time_value, state)
        return EvidenceGradient(
            gradient=zeros,
            strong=strong,
            weak=weak,
            guided=strong,
            current_rate=zero_rate,
            future_rate=zero_rate,
            value=zero_rate,
            future_state=state,
            future_time=time_value,
        )

    gamma = float(gamma_at(scalar_time))
    beta = 1.0 + gamma
    strong, weak = evaluate_pair(time_value, state)
    gap = strong - weak
    guided = strong + gamma * gap
    current_times = time_value.expand(len(state))
    current_rate = normalized_flow_evidence_rate(
        gap,
        time_value=current_times,
        beta=beta,
    )

    future_time = time_value + time_value.new_tensor(step)
    future_state = state + step * guided
    future_gamma = float(gamma_at(float(future_time.detach().float().item())))
    future_beta = 1.0 + future_gamma
    future_strong, future_weak = evaluate_pair(future_time, future_state)
    future_rate = normalized_flow_evidence_rate(
        future_strong - future_weak,
        time_value=future_time.expand(len(state)),
        beta=future_beta,
    )
    value = 0.5 * step * (current_rate + future_rate)
    gradient = torch.autograd.grad(
        value.sum(),
        state,
        create_graph=create_graph,
        retain_graph=create_graph,
    )[0]
    return EvidenceGradient(
        gradient=gradient,
        strong=strong,
        weak=weak,
        guided=guided,
        current_rate=current_rate,
        future_rate=future_rate,
        value=value,
        future_state=future_state,
        future_time=future_time,
    )


def pfr_revision(
    state: Tensor,
    time_value: Tensor,
    *,
    strong: Tensor,
    weak: Tensor,
    guided: Tensor,
    gamma: float,
    horizon: float,
    intervention_time: float,
    evaluate_weak: Callable[[Tensor, Tensor], Tensor],
) -> tuple[Tensor, Tensor, Tensor, Tensor]:
    """Return the deployed PFR revision and its counterfactual query."""

    scalar_time = float(time_value.detach().float().item())
    step = min(float(horizon), float(intervention_time) - scalar_time)
    if step <= 0.0 or gamma == 0.0:
        zeros = torch.zeros_like(state)
        coefficient = torch.zeros(len(state), device=state.device)
        return zeros, state, weak, coefficient
    beta = 1.0 + float(gamma)
    calibration = beta * (strong - weak)
    ray = project_to_forward_ray(calibration, guided)
    future_time = time_value + time_value.new_tensor(step)
    query_state = state + step * ray.parallel
    weak_query = evaluate_weak(future_time, query_state)
    return beta * (weak - weak_query), query_state, weak_query, ray.coefficient

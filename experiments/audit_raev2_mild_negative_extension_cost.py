"""CPU-only accounting after all four fixed extension workers finish.

Produces immutable request.json, summary.json, cohort_costs.csv and totals.csv.
Only recommends whether official201 must be replaced by one larger uniform K;
does not launch jobs, read images/features/FID, release evaluation, or assert
fair total research cost. --self-test exercises rounding/accounting boundaries.
"""
from __future__ import annotations

import argparse
import csv
from datetime import datetime, timezone
from fractions import Fraction
import hashlib
import json
import math
from pathlib import Path
import time

ROOT = Path(__file__).resolve().parents[1]
RESTART = Path('/home/zhoushunyu/data/eqvae/experiments/raev2_guidance_restart_20260906')
EXTENSION = RESTART / 'scale_extension_5k_v1'
PLAN_SHA = '55554188eeb66f2de867b58a0ef41f981a92e8aa0bb6688d89d19d7dcc39c159'
METRICS = (
    'trajectory_through_decode_wall_seconds', 'trajectory_plus_decode_component_sum_seconds',
    'runner_wall_seconds', 'outer_wall_seconds', 'stage2_forward_calls',
    'stage2_sample_forwards', 'decoder_forward_calls', 'decoder_sample_forwards',
)


def sha256(path):
    h = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b''):
            h.update(chunk)
    return h.hexdigest()


def identity(path):
    path = Path(path).absolute()
    return {'path': str(path), 'resolved_path': str(path.resolve()),
            'sha256': sha256(path), 'size_bytes': path.stat().st_size}


def number(value, name, *, positive=False):
    if type(value) not in (int, float) or not math.isfinite(value) or value < 0 or (positive and value <= 0):
        raise ValueError(f'invalid {name}: {value}')
    return value


def exact(value):
    number(value, 'cost')
    return Fraction(value)


def ceil_exact(value):
    return -(-value.numerator // value.denominator)


def fraction_record(value):
    return {'numerator': value.numerator, 'denominator': value.denominator, 'value': float(value)}


def aggregate(rows):
    result = {'cohorts': len(rows), 'sample_count': sum(row['samples'] for row in rows)}
    for key in METRICS:
        known = [row[key] for row in rows if row[key] is not None]
        total = sum((exact(value) for value in known), Fraction(0))
        result[key] = {'value': float(total) if len(known) == len(rows) else None,
                       'known_subtotal': float(total), 'known_exact_sum': fraction_record(total),
                       'available_cohorts': len(known), 'missing_cohorts': len(rows) - len(known),
                       'complete': len(known) == len(rows)}
    forwards = result['stage2_sample_forwards']['value']
    result['stage2_nfe_per_sample'] = (forwards / result['sample_count']
                                       if forwards is not None and result['sample_count']
                                       and not any(row.get('parity', False) for row in rows) else None)
    result['sample_count_scope'] = ('Sum sampled image counts; per-parity starting states are included where present and are not new evaluation images.'
                                    if any(row.get('parity', False) for row in rows) else 'Sum images generated by the included physical jobs, including discarded cost-only jobs when present.')
    return result


def cost_decision(candidate_rows, official_rows, k=201):
    if type(k) is not int or k < 100 or len(candidate_rows) != len(official_rows) or not candidate_rows:
        raise ValueError('need paired nonempty cohort lists and an integer official step count')
    quantities = {}
    ratios = []
    covers = []
    for key in ('trajectory_through_decode_wall_seconds', 'runner_wall_seconds'):
        c = sum((exact(number(row[key], key, positive=True)) for row in candidate_rows), Fraction(0))
        b = sum((exact(number(row[key], key, positive=True)) for row in official_rows), Fraction(0))
        ratio = Fraction(k) * c / b
        covers.append(b >= c)
        ratios.append(ceil_exact(ratio))
        quantities[key] = {'candidate': fraction_record(c), 'official': fraction_record(b),
                           'official_covers_candidate': b >= c,
                           'official_relative_excess': float((b - c) / c),
                           'exact_scaled_step_ratio': fraction_record(ratio),
                           'ceil_scaled_step_ratio': ceil_exact(ratio)}
    covered = all(covers)
    return {'official_steps': k, 'paired_cohorts': len(candidate_rows),
            'both_recorded_metrics_covered': covered,
            'suggested_uniform_steps': k if covered else max(k + 1, *ratios),
            'requires_five_new_official_cohorts': not covered,
            'metrics': quantities,
            'rule': 'retain K if both pooled T and W cover; otherwise max(K+1,ceil(K*Tc/Tb),ceil(K*Wc/Wb))',
            'limits': 'Exact arithmetic on stored binary64 timing values; timings remain noisy point estimates. Suggestion only; no evaluation release or total-cost guarantee.'}


def extract(summary, *, name, cohort_index, directory, outer=None, parity=False):
    if summary.get('complete') is not True:
        raise ValueError(f'incomplete summary: {directory}')
    is_legacy = 'full_sample_evaluations' in summary
    counts = summary.get('forward_counts_observed', summary)
    samples = summary.get('samples_per_loop') if parity else summary.get('samples')
    if samples != (16 if parity else 1000):
        raise ValueError(f'wrong sample count in {directory}: {samples}')
    trajectory = summary.get('trajectory_wall_seconds')
    decode = summary.get('decode_and_uint8_wall_seconds')
    components = float(exact(trajectory) + exact(decode)) if trajectory is not None and decode is not None else None
    runner = summary.get('elapsed_seconds') if is_legacy else summary.get('total_wall_seconds_before_summary')
    number(runner, 'runner wall', positive=True)
    row = {'name': name, 'cohort_index': cohort_index, 'directory': str(directory),
           'samples': samples, 'seed': summary.get('seed'), 'parity': parity,
           'trajectory_through_decode_wall_seconds': summary.get('trajectory_through_decode_wall_seconds'),
           'trajectory_plus_decode_component_sum_seconds': components,
           'runner_wall_seconds': runner, 'outer_wall_seconds': outer,
           'runner_metric_source': 'elapsed_seconds' if is_legacy else 'total_wall_seconds_before_summary',
           'stage2_forward_calls': summary.get('full_model_calls') if is_legacy else counts.get('stage2_forward_calls'),
           'stage2_sample_forwards': summary.get('full_sample_evaluations') if is_legacy else counts.get('stage2_sample_forwards'),
           'decoder_forward_calls': None if is_legacy else counts.get('decoder_forward_calls'),
           'decoder_sample_forwards': None if is_legacy else counts.get('decoder_sample_forwards')}
    for key in METRICS:
        if row[key] is not None:
            number(row[key], key)
    if not parity:
        expected_nfe = 200 if name == 'reflection100' else (201 if '201' in name else (200 if '200' in name else 100))
        if row['stage2_sample_forwards'] != 1000 * expected_nfe or row['stage2_forward_calls'] != 125 * expected_nfe:
            raise ValueError(f'wrong main-model accounting in {directory}')
        row['stage2_nfe_per_sample'] = expected_nfe
    else:
        row['stage2_nfe_per_sample'] = None
    return row


def run(extension, output, expected_sha):
    started = time.perf_counter()
    sources = {}
    def read(path, expected=None):
        record = identity(path)
        if expected is not None and record['sha256'] != expected:
            raise ValueError(f'changed input: {path}')
        sources[str(Path(path).resolve())] = record
        return json.loads(Path(path).read_text())
    if output.exists():
        raise FileExistsError(f'refusing to overwrite cost decision: {output}')
    plan = read(extension / 'plan.json', expected_sha)
    if plan.get('protocol') != 'raev2_mild_negative_fixed_1k_to_5k_extension_v1':
        raise ValueError('unexpected extension plan')
    document = identity(plan['protocol_document']['path'])
    if document['sha256'] != plan['protocol_document']['sha256']:
        raise ValueError('frozen protocol document changed')
    sources[document['resolved_path']] = document
    historical_outer = {}
    old_execution_path = RESTART / 'affine_reflection_v1/screen_execution.json'
    old_execution = read(old_execution_path)
    if old_execution.get('complete') is not True:
        raise ValueError('historical reflection execution not complete')
    historical_evaluation = []
    for job in old_execution['jobs']:
        if job.get('exit_code') != 0:
            raise ValueError('historical reflection contains failed job')
        if job['name'] == 'evaluation':
            historical_evaluation.append({'source': str(old_execution_path), 'job': job['name'],
                                          'outer_wall_seconds': job['outer_wall_seconds'],
                                          'scope': 'historical evaluator only; not sampling or trajectory cost'})
        else:
            historical_outer[job['name']] = job['outer_wall_seconds']
    old = {}
    for name, info in plan['historical_1k'].items():
        record = info['artifacts']['summary.json']
        summary = read(record['path'], record['sha256'])
        outer_name = {'reflection_official100': 'official100', 'reflection_official201': 'official201',
                      'reflection_official200_cost_only': 'official200', 'reflection100': 'reflection100'}.get(name)
        old[name] = extract(summary, name=name, cohort_index=0, directory=info['directory'],
                            outer=historical_outer.get(outer_name))
        old[name]['summary'] = sources[str(Path(record['path']).resolve())]
    new = {job['name']: [] for job in plan['cohorts'][0]['jobs']}
    worker_walls = []
    for cohort in plan['cohorts']:
        index = cohort['index']
        execution_path = extension / f'cohort_{index}/execution.json'
        execution = read(execution_path)
        if (execution.get('complete') is not True or execution.get('terminal') is not True
                or execution.get('fid_started') is not False or execution.get('plan_sha256') != expected_sha
                or execution.get('cohort_index') != index or execution.get('seed') != cohort['seed']
                or execution.get('gpu') != cohort['gpu']):
            raise ValueError(f'worker is incomplete or has mismatched identity: {execution_path}')
        if len(execution['jobs']) != len(cohort['jobs']):
            raise ValueError('worker job count differs from frozen plan')
        worker_walls.append(number(execution['worker_outer_wall_seconds'], 'worker wall', positive=True))
        for job, planned in zip(execution['jobs'], cohort['jobs'], strict=True):
            if (job.get('name') != planned['name'] or job.get('argv') != planned['argv']
                    or job.get('output_dir') != planned['output_dir'] or job.get('gpu') != cohort['gpu']
                    or job.get('exit_code') != 0):
                raise ValueError(f'job mismatch/failure in {execution_path}')
            record = job['summary']
            if Path(record['path']).resolve() != (Path(job['output_dir']) / 'summary.json').resolve():
                raise ValueError('summary path mismatch')
            summary = read(record['path'], record['sha256'])
            row = extract(summary, name=job['name'], cohort_index=index, directory=job['output_dir'],
                          outer=number(job['outer_wall_seconds'], 'job outer wall', positive=True),
                          parity='parity16' in job['name'])
            if row['seed'] != cohort['seed']:
                raise ValueError('summary seed differs from frozen cohort')
            row['summary'] = sources[str(Path(record['path']).resolve())]
            row['gpu'] = cohort['gpu']
            new[job['name']].append(row)
    families = {}
    mappings = {
        'global_proximal': {'candidate': ('global_proximal100', 'global_proximal100'),
                            'official100': ('legacy_official100', 'legacy_official100')},
        'legacy_energy_ball': {'candidate': ('legacy_energy100', 'legacy_energy100'),
                               'official100': ('legacy_official100', 'legacy_official100')},
        'native_global_ball': {'candidate': ('native_global100', 'native_global100'),
                               'official100': ('spatial_official100', 'native_official100')},
        'affine_reflection': {'candidate': ('reflection100', 'reflection100'),
                              'official100': ('reflection_official100', 'native_official100'),
                              'official201': ('reflection_official201', 'native_official201')},
    }
    table = []
    for family, arms in mappings.items():
        families[family] = {}
        for arm, (old_name, new_name) in arms.items():
            groups = {'old1k': [old[old_name]], 'new4k': new[new_name], 'pooled5k': [old[old_name], *new[new_name]]}
            families[family][arm] = {group: aggregate(rows) for group, rows in groups.items()}
            for group, result in families[family][arm].items():
                table.append({'family': family, 'arm': arm, 'group': group, 'sample_count': result['sample_count'],
                              'stage2_nfe_per_sample': result['stage2_nfe_per_sample'],
                              **{key: result[key]['value'] for key in METRICS}})
    decisions = {
        'old1k_descriptive': cost_decision([old['reflection100']], [old['reflection_official201']]),
        'new4k_descriptive': cost_decision(new['reflection100'], new['native_official201']),
        'pooled5k_protocol_decision': cost_decision([old['reflection100'], *new['reflection100']],
                                                  [old['reflection_official201'], *new['native_official201']]),
    }
    decision = decisions['pooled5k_protocol_decision']
    decision['all_five_uniform_K_required_before_final_cost_claim'] = True
    decision['new4k_and_old1k_separate_results_do_not_override_pooled5k_protocol_rule'] = True
    decision['next_action'] = ('keep official201 for all five reflection cohorts; no job launch authorized by this script'
                               if decision['both_recorded_metrics_covered'] else
                               f'Before FID, root must freeze and run official{decision["suggested_uniform_steps"]} on all five seeds; retain all official201 and historical official200 costs.')
    all_sampling = list(old.values()) + [row for name, rows in new.items() if 'parity16' not in name for row in rows]
    new_parity = [row for name, rows in new.items() if 'parity16' in name for row in rows]
    historical_parity = []
    for name in ('spatial_energy_balls_v1', 'affine_reflection_v1'):
        path = RESTART / name / 'parity16/summary.json'
        summary = read(path)
        historical_parity.append(extract(summary, name=name + '_parity16', cohort_index=0,
                                          directory=path.parent, parity=True))
    unique_paths = [str(Path(row['directory']).resolve()) for row in all_sampling]
    if len(set(unique_paths)) != len(unique_paths):
        raise AssertionError('duplicate physical job in aggregate accounting')
    all_rows = [*all_sampling, *new_parity, *historical_parity]
    result = {'complete': True, 'protocol': 'raev2_mild_negative_extension_cost_review_v1',
              'created_at_utc': datetime.now(timezone.utc).isoformat(), 'root_plan_sha256': expected_sha,
              'families': families, 'reflection201_decisions': decisions,
              'official201_current_role': ('pooled5K inference cost baseline' if decision['both_recorded_metrics_covered']
                                           else 'cost-only insufficient baseline; retain costs and wait for one larger uniform K on all five seeds'),
              'native_global_additional_new4k_reference': aggregate(new['native_official201']),
              'native_global_additional_reference_limit': 'Same new seeds, conditional on separate native parity/noise audit; no old spatial-seed official201 exists, so this is not a pooled5K cost baseline.',
              'cost_only_historical_official200': old['reflection_official200_cost_only'],
              'physical_sampling_jobs_once': aggregate(all_sampling),
              'new_parity_jobs_once': aggregate(new_parity),
              'historical_parity_jobs_once': aggregate(historical_parity),
              'accounted_sampling_and_parity_once': aggregate(all_rows),
              'historical_reflection_evaluation_recorded_separately': historical_evaluation,
              'new_worker_outer_wall_sum_seconds': float(sum((exact(v) for v in worker_walls), Fraction(0))),
              'new_worker_outer_wall_scope': 'Sum four sequential-worker elapsed times, includes worker overhead/gaps. Overlaps child job times; never add this to job costs or call it parallel elapsed duration.',
              'missing_costs_and_scope': [
                  'Historical legacy and spatial process outer wall is unavailable here; null totals preserve missingness.',
                  'Legacy elapsed_seconds includes load/preparation/sample/decode/I/O; no separated trajectory T or observed decoder-call count exists.',
                  'Spatial trajectory+decode component sum differs from the reflection whole-span T; both fields are kept distinct.',
                  'Candidate calibration, historical data acquisition, training, rejected earlier studies, this CPU audit and evaluator costs are not all closed by these sampling summaries.',
                  'Family tables reuse shared baselines for comparisons; physical job accounting deduplicates them and includes the discarded historical official200.',
                  'Per-process wall on allocated GPUs is an elapsed cost proxy, not measured integrated GPU busy time; four-card parallel duration is not total compute.',
                  'Old1K FID was already inspected when choosing candidates. This cost-only script reads no FID, features, pixels or future metric.',
              ], 'fair_total_research_cost_closed': False, 'quality_or_sota_claim': False,
              'evaluation_released': False, 'new_jobs_launched': False,
              'cpu_audit_wall_seconds_before_write': time.perf_counter() - started}
    output.mkdir(parents=True, exist_ok=False)
    request = {'created_at_utc': datetime.now(timezone.utc).isoformat(), 'source': identity(Path(__file__)),
               'inputs': sources, 'scope': 'CPU-only, completed frozen plans/executions/summaries; no image/model/FID reads'}
    for filename, payload in [('request.json', request), ('summary.json', result)]:
        with (output / filename).open('x') as stream:
            json.dump(payload, stream, indent=2, allow_nan=False)
            stream.write('\n')
    for filename, rows in [('totals.csv', table), ('cohort_costs.csv', all_rows)]:
        fields = (list(table[0]) if filename == 'totals.csv' else
                  ['name', 'cohort_index', 'samples', 'seed', 'parity', 'directory', 'runner_metric_source', *METRICS])
        with (output / filename).open('x', newline='') as stream:
            writer = csv.DictWriter(stream, fieldnames=fields, extrasaction='ignore')
            writer.writeheader()
            writer.writerows(rows)
    print(json.dumps({'output': str(output), 'summary': identity(output / 'summary.json'),
                      'pooled5k_reflection201_covered': decision['both_recorded_metrics_covered'],
                      'suggested_uniform_K': decision['suggested_uniform_steps'], 'evaluation_released': False}))


def self_test():
    def row(t, w):
        return {'trajectory_through_decode_wall_seconds': t, 'runner_wall_seconds': w}
    assert ceil_exact(Fraction(201)) == 201
    assert ceil_exact(Fraction(201 * (2**53) + 1, 2**53)) == 202
    assert cost_decision([row(1., 1.)], [row(1., 1.)])['suggested_uniform_steps'] == 201
    assert cost_decision([row(1., math.nextafter(1., math.inf))], [row(1., 1.)])['suggested_uniform_steps'] == 202
    assert cost_decision([row(math.nextafter(1., math.inf), 1.)], [row(1., 1.)])['suggested_uniform_steps'] == 202
    assert cost_decision([row(3., 2.)], [row(2., 2.)])['suggested_uniform_steps'] == 302
    # Exact summation preserves a low-order difference lost by binary64 sum.
    d = cost_decision([row(2**53, 2**53), row(1., 1.)], [row(2**53, 2**53), row(.5, .5)])
    assert not d['both_recorded_metrics_covered'] and d['suggested_uniform_steps'] == 202
    r = {'samples': 1000, **{key: None for key in METRICS}}
    r['runner_wall_seconds'] = 5.
    a = aggregate([r])
    assert a['trajectory_through_decode_wall_seconds']['value'] is None
    assert a['trajectory_through_decode_wall_seconds']['known_subtotal'] == 0.
    assert not a['trajectory_through_decode_wall_seconds']['complete']
    assert a['runner_wall_seconds']['value'] == 5.
    try:
        cost_decision([row(None, 1.)], [row(1., 1.)])
    except ValueError:
        pass
    else:
        raise AssertionError('missing T must refuse a cost decision')
    print(json.dumps({'self_test': 'passed', 'scope': 'exact ceil, float-neighbor and pooled-sum boundaries, missing cost remains null'}))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--extension-dir', type=Path, default=EXTENSION)
    parser.add_argument('--plan-sha256', default=PLAN_SHA)
    parser.add_argument('--output-dir', type=Path)
    parser.add_argument('--self-test', action='store_true')
    args = parser.parse_args()
    if args.self_test:
        self_test()
    else:
        run(args.extension_dir, args.output_dir or args.extension_dir / 'cost_review_v1', args.plan_sha256)


if __name__ == '__main__':
    main()
